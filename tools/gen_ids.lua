-- Generates addons/clickheal/ch/spell_ids.lua from LandSandBoat's spell_list.sql and abilities.sql.
-- Usage: lua tools/gen_ids.lua <spell_list.sql> <abilities.sql>
package.path = 'addons/clickheal/?.lua;' .. package.path
local spells = require('ch.spells')

local function slug(name) return (name:lower():gsub("'", ''):gsub('[^%w]+', '_'):gsub('^_+', ''):gsub('_+$', '')) end

local sp = {}
for l in io.lines(arg[1]) do
    local id, name = l:match("^INSERT INTO `spell_list` VALUES %((%d+),'([%w_]+)'")
    if id then sp[name] = tonumber(id) end
end
local ab = {}
for l in io.lines(arg[2]) do
    local name, rid = l:match("^INSERT INTO `abilities` VALUES %(%d+,'([%w_]+)',%d+,%d+,%d+,%d+,(%d+)")
    if name then ab[name] = tonumber(rid) end
end

local keys = {}
for k in pairs(spells.defs) do keys[#keys + 1] = k end
table.sort(keys)
local out, miss = {}, {}
for _, k in ipairs(keys) do
    local d = spells.defs[k]
    local s = slug(d.name)
    if d.ja then
        if ab[s] ~= nil then out[#out + 1] = string.format("    %s = { ability = %d },", k, ab[s]) else miss[#miss + 1] = k end
    else
        if sp[s] then out[#out + 1] = string.format("    %s = { spell = %d },", k, sp[s]) else miss[#miss + 1] = k end
    end
end
local f = assert(io.open('addons/clickheal/ch/spell_ids.lua', 'wb'))
f:write("--[[\n    ClickHeal - spell_ids.lua   (generated by tools/gen_ids.lua; do not edit by hand)\n")
f:write("    Game ids per spell key: `spell` = spell id for the recast timer, `ability` = ability recast id\n")
f:write("    (0 = the 2-hour ability slot). Source: LandSandBoat spell_list / abilities tables.\n]]--\n\nreturn {\n")
f:write(table.concat(out, '\n'), '\n}\n')
f:close()
print(#out .. ' mapped; unmatched: ' .. table.concat(miss, ' '))
