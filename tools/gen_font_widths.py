#!/usr/bin/env python3
"""
Writes tools/font_widths.lua: the advance width of every printable ASCII character in Segoe UI (the font the
setup panel uses in game), in 1/1000 em. tools/dump_config.lua uses it so the setup-panel previews measure text
the way the game does. Run once; the output is committed.

    python tools/gen_font_widths.py
"""
import os
from PIL import ImageFont

FONT = os.path.join(os.environ.get("WINDIR", "C:/Windows"), "Fonts", "segoeui.ttf")
f = ImageFont.truetype(FONT, 1000)
rows = []
for code in range(32, 127):
    rows.append("[%d]=%d" % (code, round(f.getlength(chr(code)))))
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "font_widths.lua"), "w", newline="\n") as out:
    out.write("-- Generated by tools/gen_font_widths.py: Segoe UI advance widths, 1/1000 em.\n")
    out.write("return { em = 1000, avg = %d, w = {\n    %s,\n} }\n" % (round(f.getlength("n")), ",\n    ".join(", ".join(rows[i:i + 8]) for i in range(0, len(rows), 8))))
print("wrote tools/font_widths.lua")
